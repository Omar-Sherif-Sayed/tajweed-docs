"""Write the Quran sample into the design prototype pages.

The prototypes must show real Quran text, and nobody may type it (parent AGENTS.md, rule 6.1). This script copies
a few ayahs from the untouched Tanzil file into the marked data block of each prototype page. It never changes a
character of the text, and it stops if the source file's checksum is not the recorded one.

Run from anywhere:  python build_quran_sample.py
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "..", "assets", "tanzil", "quran-uthmani.txt")
TARGET_PAGES = ["round-1.html"]   # design 1: the reading view by surah

# SHA-256 of the file downloaded from tanzil.net on 2026-11-17 (see assets/tanzil/README.md).
EXPECTED_SHA256 = "6933e133dd56db778c801bf738848454e43648105a151e8d84d86a7cae39ec5f"

# What the prototypes show: (surah, first ayah, last ayah).
WANTED = [(1, 1, 7), (2, 1, 5)]


def main():
    raw = open(SOURCE, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit("The Tanzil file changed: " + digest)

    ayahs = {}   # (surah, ayah) -> text
    counts = {}  # surah -> number of ayahs
    for line in raw.decode("utf-8").split("\n"):
        parts = line.rstrip("\r").split("|", 2)
        if len(parts) == 3 and parts[0].isdigit() and parts[1].isdigit():
            surah, ayah = int(parts[0]), int(parts[1])
            ayahs[(surah, ayah)] = parts[2]
            counts[surah] = counts.get(surah, 0) + 1
    if len(ayahs) != 6236 or len(counts) != 114:
        raise SystemExit("Unexpected counts: %d ayahs, %d surahs" % (len(ayahs), len(counts)))

    basmala = ayahs[(1, 1)]
    surahs = []
    for surah, first, last in WANTED:
        rows = []
        for number in range(first, last + 1):
            text = ayahs[(surah, number)]
            starts_with_basmala = surah != 1 and number == 1 and text.startswith(basmala + " ")
            rows.append({
                "number": number,
                # Display layer only: the basmala that opens the surah is shown on its own line.
                "basmala": basmala if starts_with_basmala else None,
                "text": text[len(basmala) + 1:] if starts_with_basmala else text,
            })
        surahs.append({"surah": surah, "ayahCount": counts[surah], "ayahs": rows})

    data = {
        "source": "Tanzil Quran Text (Uthmani, Version 1.1) - https://tanzil.net",
        "sourceSha256": digest,
        "totalAyahs": len(ayahs),
        "ayahCounts": {str(s): counts[s] for s in range(1, 6)},
        "surahs": surahs,
    }
    header = (
        "/*\n"
        " * Generated by tools/build_quran_sample.py - do not edit by hand.\n"
        " * Quran text: Tanzil Quran Text (Uthmani, Version 1.1), Copyright (C) 2007-2026 Tanzil Project,\n"
        " * License: Creative Commons Attribution 3.0 - https://tanzil.net\n"
        " * The text is copied without any change. Changing it is not allowed.\n"
        " */\n"
    )
    block = header + "window.QURAN_SAMPLE = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"

    # The prototype pages are single files, so that they open anywhere (a browser, the repository viewer):
    # the data block is written into each page between two marker comments.
    begin, end = "/*QURAN-SAMPLE-BEGIN*/", "/*QURAN-SAMPLE-END*/"
    for name in TARGET_PAGES:
        path = os.path.join(HERE, "..", name)
        page = open(path, encoding="utf-8", newline="").read()
        if page.count(begin) != 1 or page.count(end) != 1:
            raise SystemExit(name + ": the two marker comments were not found exactly once")
        head, rest = page.split(begin)
        tail = rest.split(end)[1]
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(head + begin + "\n" + block + end + tail)
        print("written into", name, "-", sum(len(s["ayahs"]) for s in surahs), "ayahs")


if __name__ == "__main__":
    main()
